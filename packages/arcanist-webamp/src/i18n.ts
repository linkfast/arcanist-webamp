const spanish = navigator.language.toLowerCase().startsWith("es");
/** The language of the texts, for dates and times. */
export const language = spanish ? "es" : "en";
const dictionary: Record<Key, string> = spanish ? es : en;

export function t(key: Key, params: Record<string, string | number> = {}): string {
  // A count of one takes the singular, when the text has one ("<key>.one").
  const one = `${key}.one` as Key;
  const text = params.count === 1 && one in dictionary ? dictionary[one] : dictionary[key];
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}

/** A message for an API error code. */
export function errorText(code: string): string {
  const key = `error.${code}` as Key;
  return key in dictionary ? dictionary[key] : t("error.generic", { code });
}

export type { Key as TextKey };
